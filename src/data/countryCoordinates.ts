const WORLD_MAP_BASE_WIDTH = 960;
const WORLD_MAP_BASE_HEIGHT = 720;

const D3_TRANSLATE_X = 480;
const D3_TRANSLATE_Y = 250;

const WORLD_MAP_VERTICAL_OFFSET = 240;


const MERCATOR_SCALE = 961 / (2 * Math.PI);


const MAX_MERCATOR_LATITUDE = 85.05112878;

export function coordsToPosition(lat: number, lng: number) {
  const safeLatitude = Math.max(
    -MAX_MERCATOR_LATITUDE,
    Math.min(MAX_MERCATOR_LATITUDE, lat),
  );

  const safeLongitude = Math.max(-180, Math.min(180, lng));

  const longitudeRadians = (safeLongitude * Math.PI) / 180;
  const latitudeRadians = (safeLatitude * Math.PI) / 180;


  const projectedX =
    D3_TRANSLATE_X + MERCATOR_SCALE * longitudeRadians;

  const projectedY =
    D3_TRANSLATE_Y -
    MERCATOR_SCALE *
      Math.log(
        Math.tan(
          Math.PI / 4 + latitudeRadians / 2,
        ),
      );

  const left =
    (projectedX / WORLD_MAP_BASE_WIDTH) * 100;

  const top =
    ((projectedY + WORLD_MAP_VERTICAL_OFFSET) /
      WORLD_MAP_BASE_HEIGHT) *
    100;

  return {
    left: `${left}%`,
    top: `${top}%`,
  };
}

export function getCountryCoordinates(countryName: string) {
  if (!countryName) return null;

  const trimmed = countryName.trim();

  if (COUNTRY_COORDINATES[trimmed]) {
    return COUNTRY_COORDINATES[trimmed];
  }

  const lowerTarget = trimmed.toLowerCase();
  const matchKey = Object.keys(COUNTRY_COORDINATES).find(
    (key) => key.toLowerCase() === lowerTarget
  );

  return matchKey ? COUNTRY_COORDINATES[matchKey] : null;
}

// Returns the lowercase ISO alpha-2 code react-svg-worldmap needs
// in its `data` prop to highlight a country's shape.
export function getCountryIsoCode(countryName: string): string | null {
  if (!countryName) return null;

  const trimmed = countryName.trim();

  if (COUNTRY_ISO_CODES[trimmed]) {
    return COUNTRY_ISO_CODES[trimmed];
  }

  const lowerTarget = trimmed.toLowerCase();
  const matchKey = Object.keys(COUNTRY_ISO_CODES).find(
    (key) => key.toLowerCase() === lowerTarget
  );

  return matchKey ? COUNTRY_ISO_CODES[matchKey] : null;
}